// Package forward breaks dependency cycles between services built in the same Golang namespace (a process, a test
// harness): Tomislav-RetCtx.
//
// When service A's constructor needs B and B's constructor needs A, the wiring namespace detects that A is requested
// while it is still being built (see wiring.ForwardReferencer) and gives B a forward Reference instead of A. In the
// generated code the Reference is a small stub that implements A's interface: B's constructor receives the stub, and
// every call on it is forwarded to A, which the stub looks up by name in the runtime namespace on first use. By then A
// has been built. A call made while A is still being built (a constructor on the cycle calling the other service)
// returns an error instead of starting a second build.
//
// Across processes no Reference is needed: a service deployed over RPC is reached through its address, and the
// server side behind an address is built lazily, so A's and B's processes each build only a client of the other.
package forward

import (
	"fmt"
	"path/filepath"

	"github.com/blueprint-uservices/blueprint/blueprint/pkg/blueprint"
	"github.com/blueprint-uservices/blueprint/blueprint/pkg/coreplugins/service"
	"github.com/blueprint-uservices/blueprint/blueprint/pkg/ir"
	"github.com/blueprint-uservices/blueprint/plugins/golang"
	"github.com/blueprint-uservices/blueprint/plugins/golang/gocode"
	"github.com/blueprint-uservices/blueprint/plugins/golang/gogen"
	"golang.org/x/exp/slog"
)

// The package, within the generated module, that holds the generated stubs.
const outputPackage = "forward"

// Reference is the Blueprint IR node that stands for the service Target on a dependency cycle.
type Reference struct {
	golang.Service
	golang.GeneratesFuncs
	golang.Instantiable

	InstanceName string // name of this node: Target + ".forward"
	Target       string // the node this reference stands for

	resolve func() (ir.IRNode, error) // returns the node Target once the namespace has built it
}

// New returns the forward reference for `name`; resolve must return the node `name` once it has been built.
func New(name string, resolve func() (ir.IRNode, error)) *Reference {
	return &Reference{InstanceName: name + ".forward", Target: name, resolve: resolve}
}

func (r *Reference) ImplementsGolangNode()    {}
func (r *Reference) ImplementsGolangService() {}

func (r *Reference) Name() string {
	return r.InstanceName
}

func (r *Reference) String() string {
	return r.InstanceName + " = ForwardReference(" + r.Target + ")"
}

// The service this reference stands for. Only available after the namespace has finished building.
func (r *Reference) target() (golang.Service, error) {
	node, err := r.resolve()
	if err != nil {
		return nil, err
	}
	svc, isService := node.(golang.Service)
	if !isService {
		return nil, blueprint.Errorf("forward reference %s: %s is a %T, not a golang service; only services can close a dependency cycle", r.InstanceName, r.Target, node)
	}
	return svc, nil
}

// Implements service.ServiceNode: the interface of the target.
func (r *Reference) GetInterface(ctx ir.BuildContext) (service.ServiceInterface, error) {
	target, err := r.target()
	if err != nil {
		return nil, err
	}
	return target.GetInterface(ctx)
}

// Implements golang.ProvidesInterface: the target's interface, nothing of its own.
func (r *Reference) AddInterfaces(builder golang.ModuleBuilder) error {
	target, err := r.target()
	if err != nil {
		return err
	}
	return target.AddInterfaces(builder)
}

// Implements golang.GeneratesFuncs: one stub type per service interface and module.
func (r *Reference) GenerateFuncs(builder golang.ModuleBuilder) error {
	target, err := r.target()
	if err != nil {
		return err
	}
	iface, err := golang.GetGoInterface(builder, target)
	if err != nil {
		return err
	}
	if builder.Visited("forward-stub:" + iface.UserType.Package + "." + iface.UserType.Name) {
		return nil
	}
	return generateStub(builder, iface)
}

// Implements golang.Instantiable: at runtime the node is a stub that reaches the target by its name.
func (r *Reference) AddInstantiation(builder golang.NamespaceBuilder) error {
	if builder.Visited(r.InstanceName) {
		return nil
	}
	target, err := r.target()
	if err != nil {
		return err
	}
	iface, err := golang.GetGoInterface(builder, target)
	if err != nil {
		return err
	}
	constructor := builder.ImportType(&gocode.UserType{
		Package: builder.Module().Info().Name + "/" + outputPackage,
		Name:    "New_" + stubName(iface),
	})
	code := fmt.Sprintf(`func(n *golang.Namespace) (any, error) {
		// Auto-generated by plugins/golang/forward: stands for %v on a dependency cycle
		return %v(n, %q), nil
	}`, target.Name(), constructor, target.Name())
	return builder.Declare(r.InstanceName, code)
}

func stubName(iface *gocode.ServiceInterface) string {
	return iface.BaseName + "_Forward"
}

type stubArgs struct {
	Package golang.PackageInfo
	Service *gocode.ServiceInterface
	Name    string
	Imports *gogen.Imports
}

func generateStub(builder golang.ModuleBuilder, iface *gocode.ServiceInterface) error {
	pkg, err := builder.CreatePackage(outputPackage)
	if err != nil {
		return err
	}
	args := stubArgs{Package: pkg, Service: iface, Name: stubName(iface), Imports: gogen.NewImports(pkg.Name)}
	args.Imports.AddPackages("context", "fmt", "sync", "sync/atomic", "github.com/blueprint-uservices/blueprint/runtime/plugins/golang")
	slog.Info(fmt.Sprintf("Generating %v/%v", pkg.PackageName, args.Name))
	return gogen.ExecuteTemplateToFile("ForwardStub", stubTemplate, args, filepath.Join(pkg.Path, args.Name+".go"))
}

// The receiver and local names start with "__" so they cannot collide with the interface's argument names.
var stubTemplate = `// Blueprint: Auto-generated by the forward-reference plugin (plugins/golang/forward)
package {{.Package.ShortName}}

{{.Imports}}

// {{.Name}} stands for a {{.Service.BaseName}} on a dependency cycle. Blueprint gives it to the constructor that closes
// the cycle, before the target exists; every call is forwarded to the target, which is looked up by name in the
// namespace on first use. A call that arrives while the target is still being built returns an error.
type {{.Name}} struct {
	namespace *golang.Namespace
	target    string
	mu        sync.Mutex
	resolved  atomic.Value
}

func New_{{.Name}}(namespace *golang.Namespace, target string) *{{.Name}} {
	return &{{.Name}}{namespace: namespace, target: target}
}

func (__fwd *{{.Name}}) get() ({{.Imports.NameOf .Service.UserType}}, error) {
	if __target, ok := __fwd.resolved.Load().({{.Imports.NameOf .Service.UserType}}); ok {
		return __target, nil
	}
	__fwd.mu.Lock()
	defer __fwd.mu.Unlock()
	if __target, ok := __fwd.resolved.Load().({{.Imports.NameOf .Service.UserType}}); ok {
		return __target, nil
	}
	if __fwd.namespace.Building(__fwd.target) {
		return nil, fmt.Errorf("%v was called while it is still being built (a constructor on a dependency cycle called it)", __fwd.target)
	}
	var __target {{.Imports.NameOf .Service.UserType}}
	if err := __fwd.namespace.Get(__fwd.target, &__target); err != nil {
		return nil, err
	}
	__fwd.resolved.Store(__target)
	return __target, nil
}

{{$receiver := .Name -}}
{{ range $_, $f := .Service.Methods }}
func (__fwd *{{$receiver}}) {{$f.Name -}} ({{ArgVarsAndTypes $f "ctx context.Context"}}) ({{RetVarsAndTypes $f "err error"}}) {
	__target, err := __fwd.get()
	if err != nil {
		return
	}
	return __target.{{$f.Name}}({{ArgVars $f "ctx"}})
}
{{end}}
`
